--
-- A note on the index this file deliberately does *not* create. The obvious addition is a
-- "recent reveals" index for the burst detector:
--
--   create index on audit_log (created_at desc) where action = 'secret.revealed';
--
-- and it is wrong twice over. Partial index predicates may not compare against a value that is
-- not a column, so `action = '…'` is legal but the index would have to be rebuilt by hand
-- whenever the action name changed; and `audit_log_action_idx` (0001) already covers `action`,
-- so a combined scan of that index with the time range is a two-index read the planner can do
-- anyway. The window a burst detector scans is one hour.
