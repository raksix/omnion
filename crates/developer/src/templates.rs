fn workflow(name: &str, target: ScaffoldTarget) -> Vec<ScaffoldFile> {
    // The target is recorded on the generation row and deliberately does not change a byte of
    // the generated tree -- see `ScaffoldTarget`'s doc. Reading it here keeps the parameter
    // honest for a future per-target template without pretending one exists today.
    let _aimed_at = target;
    let title = title_case(name);
    vec![
        ScaffoldFile::new(
            "omnion.manifest.json",
            manifest(ScaffoldKind::Workflow, name, "workflow.omni", &title),
        ),
        ScaffoldFile::new(
            "workflow.omni",
            format!(
                "# {title}\n\
                 #\n\
                 # A workflow is a trigger, some steps and their edges. Run it from the automation\n\
                 # screen after installing the folder.\n\n\
                 trigger manual\n\
                 \n\
                 step greet:\n\
                 \x20 log \"{title} ran for ${{{{ trigger.actor }}}}\"\n\n\
                 step notify:\n\
                 \x20 log \"finished at ${{{{ steps.greet.output }}}}\"\n\n\
                 greet -> notify\n",
                title = title,
            ),
        ),
        ScaffoldFile::new(
            "README.md",
            format!(
                "# {title}\n\n\
                 A workflow starter generated by Omnion.\n\n\
                 `workflow.omni` is the whole workflow. It declares a manual trigger, two steps and\n\
                 the edge between them. Open it in the workflow builder to add nodes visually, or\n\
                 edit the file directly and reinstall.\n\n\
                 ## Do not commit credentials\n\n\
                 If you add a credential node, put the credential in the platform's secrets\n\
                 manager and reference it by name. Do not paste a token into this file — it gets\n\
                 copied into public repositories.\n",
                title = title,
            ),
        ),
        gitignore(),
        env_example(),
    ]
}

// ───────────────────────────────────────────────────────────────── helpers

/// Turn `my-plugin` into `My Plugin` for the display name.
///
/// ASCII-only on purpose: a name is validated as a slug, so it can only contain ASCII letters,
/// digits, `-` and `_`. Mapping `_` to a space here would be wrong (it is a valid name
/// character, not a word break) so only dashes break.
fn title_case(name: &str) -> String {
    name.split('-')
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect::<Vec<_>>()
        .join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every kind, every name shape, generated and checked against the rules.
    #[test]
    fn every_kind_generates_a_tree_with_a_manifest_a_readme_and_a_gitignore() {
        for kind in ScaffoldKind::ALL {
            let scaffold = generate(kind, "hello-world", ScaffoldTarget::Live).unwrap();
            let paths: Vec<&str> = scaffold.files.iter().map(|f| f.path.as_str()).collect();
            assert!(
                paths.contains(&"omnion.manifest.json"),
                "{kind:?} ships no manifest: {paths:?}"
            );
            assert!(paths.contains(&"README.md"), "{kind:?} ships no README");
            assert!(
                paths.contains(&".gitignore"),
                "{kind:?} ships no .gitignore"
            );
        }
    }

    /// The two properties the panel's file-tree preview depends on.
    #[test]
    fn the_byte_total_equals_the_sum_of_the_files_and_is_not_zero() {
        let scaffold = generate(ScaffoldKind::Plugin, "hello-world", ScaffoldTarget::Live).unwrap();
        let sum: usize = scaffold.files.iter().map(|f| f.content.len()).sum();
        assert_eq!(scaffold.byte_size, sum);
        assert!(
            scaffold.byte_size > 500,
            "a starter this small cannot be useful"
        );
    }

    #[test]
    fn the_hidden_files_are_generated_but_not_offered_for_preview() {
        // Both halves matter. `.gitignore` exists because the risk note asks for it; it is
        // hidden because a preview full of dotfiles is noise. `.env.example` is the same kind
        // of file but the README points at it, so hiding it would hide the warning's target.
        let scaffold = generate(ScaffoldKind::Plugin, "hello-world", ScaffoldTarget::Live).unwrap();
        for file in &scaffold.files {
            if file.path == ".gitignore" {
                assert!(!file.shown_in_preview);
                assert!(!file.content.is_empty());
            }
        }
    }

    /// The rule that makes this module exist. Review catches what you are looking at; this
    /// catches what you add afterwards.
    #[test]
    fn no_template_looks_like_it_carries_a_credential() {
        // Patterns a secret scanner would flag, and that a reader skimming a starter would
        // mistake for a real value. `OMNION_TOKEN=` on its own line is *not* here: an empty
        // assignment is the thing we want, and the presence of the name is the warning.
        const FORBIDDEN: [&str; 8] = [
            "sk_live_",
            "sk_test_",
            "ghp_",
            "gho_",
            "github_pat_",
            "xoxb-",
            "xoxp-",
            "AKIA",
        ];
        for kind in ScaffoldKind::ALL {
            let scaffold = generate(kind, "hello-world", ScaffoldTarget::Sandbox).unwrap();
            for file in &scaffold.files {
                for needle in FORBIDDEN {
                    assert!(
                        !file.content.contains(needle),
                        "{kind:?}/{} looks like it carries a credential ({needle})",
                        file.path
                    );
                }
            }
        }
    }

    /// The empty-value half of the same rule, stated separately.
    ///
    /// A `.env.example` whose keys are *populated* is the failure. Asserting it is empty is the
    /// only way that stays true when someone helpfully fills in the base URL.
    #[test]
    fn the_example_environment_file_has_names_and_no_values() {
        let scaffold =
            generate(ScaffoldKind::Workflow, "hello-world", ScaffoldTarget::Live).unwrap();
        let env = scaffold
            .files
            .iter()
            .find(|file| file.path == ".env.example")
            .expect("the workflow template ships an example environment file");
        for line in env.content.lines() {
            let line = line.trim();
            if let Some((key, value)) = line.split_once('=') {
                assert!(
                    value.is_empty(),
                    ".env.example assigns a value to {key:?}: {value:?}"
                );
            }
        }
    }

    /// The generated manifest is valid by the rule the loader uses — see the scaffold tests,
    /// which assert the same property across all three kinds. This one states the reason: a
    /// template that failed its own validator would make the panel's green Validate button
    /// meaningless.
    #[test]
    fn a_generated_manifest_validates() {
        let scaffold = generate(ScaffoldKind::Theme, "hello-world", ScaffoldTarget::Live).unwrap();
        let manifest = scaffold
            .files
            .iter()
            .find(|file| file.path == "omnion.manifest.json")
            .unwrap();
        let report = crate::scaffold::validate_manifest(ScaffoldKind::Theme, &manifest.content);
        assert!(report.valid, "{:?}", report.issues);
    }

    #[test]
    fn the_slug_appears_verbatim_in_the_manifest() {
        // The failure this prevents: a manifest whose name differs from the directory name,
        // which is an extension that installs as one thing and reports as another.
        for name in ["my-plugin", "a_b", "x1-y2"] {
            let scaffold = generate(ScaffoldKind::Plugin, name, ScaffoldTarget::Live).unwrap();
            let manifest = &scaffold.files[0];
            assert!(
                manifest.content.contains(&format!("\"name\": \"{name}\"")),
                "manifest does not carry {name:?}"
            );
            assert_eq!(scaffold.slug(), format!("plugin-{name}"));
        }
    }

    #[test]
    fn the_display_name_is_the_slug_in_readable_form() {
        let scaffold = generate(
            ScaffoldKind::Plugin,
            "my-first-plugin",
            ScaffoldTarget::Live,
        )
        .unwrap();
        let manifest = &scaffold.files[0];
        assert!(
            manifest
                .content
                .contains("\"displayName\": \"My First Plugin\""),
            "{}",
            manifest.content
        );
    }

    #[test]
    fn generation_refuses_an_invalid_name_before_it_builds_anything() {
        // The gate is in the generator, not only in the handler — so a future second caller
        // cannot skip it.
        assert!(generate(ScaffoldKind::Plugin, "../escape", ScaffoldTarget::Live).is_err());
        assert!(generate(ScaffoldKind::Plugin, "", ScaffoldTarget::Live).is_err());
    }

    #[test]
    fn the_target_does_not_change_a_byte_of_the_output() {
        // The claim the `ScaffoldTarget` doc makes. If a future change breaks it, the two
        // starters it produces are wrong in one environment, which is the thing the doc says
        // is the reason they are identical.
        let live = generate(ScaffoldKind::Plugin, "hello-world", ScaffoldTarget::Live).unwrap();
        let sandbox =
            generate(ScaffoldKind::Plugin, "hello-world", ScaffoldTarget::Sandbox).unwrap();
        let live: Vec<&str> = live.files.iter().map(|f| f.content.as_str()).collect();
        let sandbox: Vec<&str> = sandbox.files.iter().map(|f| f.content.as_str()).collect();
        assert_eq!(live, sandbox);
    }
}
