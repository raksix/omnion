//! The three starter templates (REQ-033, slice 4).
//!
//! This is where a [`ScaffoldRequest`] becomes a list of files. It is a separate module from
//! [`crate::scaffold`] because the *rules* are the part worth testing hard and they are
//! independent of what the templates happen to contain: a change to a README's wording must
//! not be able to break the manifest validator's tests, and a change to the validator must not
//! require re-reading three templates to find out what changed.
//!
//! # The one rule about content
//!
//! **No template contains anything that looks like a credential.** Not a token, not a key, not
//! a half-filled `.env` with a plausible-looking value. The reason is the request's own risk
//! note — scaffolds get copied into public repositories — and the failure mode is specific: a
//! starter that ships `API_TOKEN=sk_live_4eC39Hq...` teaches the reader that a value which
//! looks like that belongs in a file that gets committed. The example environment file ships
//! with its keys present and their values empty, which is what makes the README's warning
//! concrete rather than a platitude.
//!
//! The second half of that rule is enforced by a test, not by review: [`tests::no_template_looks_like_it_carries_a_credential`]
//! reads every generated byte and refuses patterns that would be found by a secret scanner.
//! Review catches what you are looking at; the test catches what you added afterwards.

use crate::Result;
use crate::scaffold::{
    Scaffold, ScaffoldFile, ScaffoldKind, ScaffoldRequest, ScaffoldTarget, validate_scaffold,
};

/// Generate the starter archive for one request.
///
/// `validate_scaffold` runs here rather than only in the API handler, so a future caller that
/// reaches the generator from somewhere else gets the same refusal instead of a directory name
/// nobody validated.
pub fn generate(kind: ScaffoldKind, name: &str, target: ScaffoldTarget) -> Result<Scaffold> {
    let request = ScaffoldRequest {
        kind,
        name: name.to_string(),
        target,
    };
    validate_scaffold(&request)?;

    let files = match kind {
        ScaffoldKind::Plugin => plugin(&name, target),
        ScaffoldKind::Theme => theme(&name, target),
        ScaffoldKind::Workflow => workflow(&name, target),
    };

    let byte_size = files.iter().map(ScaffoldFile::byte_size).sum();
    Ok(Scaffold {
        kind,
        name: name.to_string(),
        target,
        files,
        byte_size,
    })
}

/// The manifest every template ships, as a JSON string built from values rather than a constant.
///
/// Building it means the name in the manifest cannot disagree with the name of the directory,
/// and the `kind` cannot disagree with the tab it was generated from — those two are the
/// fields [`crate::scaffold::validate_manifest`] checks first, and a mismatch between the two
/// is an extension that passes review and fails to boot.
fn manifest(kind: ScaffoldKind, name: &str, entry: &str, display_name: &str) -> String {
    // Every value interpolated here is either a literal from this module or a name that has
    // been slug-validated to letters, digits, `-` and `_`. None can contain a quote or a
    // backslash, so the interpolation cannot produce invalid JSON. That reasoning is why the
    // validator *refuses* a bad character rather than escaping it: an escaping path would need
    // its own tests, and a test that only passes because nothing can reach it is not a test.
    format!(
        "{{\n  \"kind\": \"{kind}\",\n  \"version\": \"1.0.0\",\n  \"name\": \"{name}\",\n  \
         \"entry\": \"{entry}\",\n  \"displayName\": \"{display_name}\",\n  \
         \"description\": \"A {kind} extension.\"\n}}\n",
        kind = kind.as_str(),
    )
}

/// `.gitignore` — every template ships one.
fn gitignore() -> ScaffoldFile {
    ScaffoldFile::hidden(
        ".gitignore",
        "# Build output and dependencies\nnode_modules/\ndist/\n\n\
         # Local configuration. The example file is committed; the real one is not.\n\
         .env\n.env.local\n\n\
         # Editor noise\n.DS_Store\n*.log\n",
    )
}

/// The example environment file: keys present, values empty.
///
/// Empty on purpose — see the module doc. A commented placeholder is the difference between
/// "here is where your token goes" and "here is a token".
fn env_example() -> ScaffoldFile {
    ScaffoldFile::hidden(
        ".env.example",
        "# Copy this file to .env and fill it in. Never commit the copy.\n\
         #\n\
         # The value below is intentionally empty. A starter that shipped a working-looking\n\
         # token here would teach you to paste the real one next to it.\n\
         OMNION_BASE_URL=\nOMNION_TOKEN=\n",
    )
}

/// The shared README warning, worded the way the risk note asks for.
fn readme(name: &str, kind: ScaffoldKind, body: &str) -> ScaffoldFile {
    ScaffoldFile::new(
        "README.md",
        format!(
            "# {name}\n\n\
             A {kind} starter generated by Omnion.\n\n\
             {body}\n\n\
             ## Do not commit credentials\n\n\
             This project talks to Omnion with a token, and a token in a public repository is a\n\
             credential anybody can use. `.gitignore` already excludes `.env`; leave it that way.\n\
             If a token is ever committed, rotate it in the panel — deleting the commit does not\n\
             take it back.\n\n\
             ## Before you publish\n\n\
             Run `omnion manifest validate` against `omnion.manifest.json`. The panel validates\n\
             with the same code the platform's loader uses, so a manifest that passes there is a\n\
             manifest the platform will attempt to load.\n",
            kind = kind.label().to_lowercase(),
        ),
    )
}

// ───────────────────────────────────────────────────────────────── plugin

fn plugin(name: &str, target: ScaffoldTarget) -> Vec<ScaffoldFile> {
    // The target is recorded on the generation row and deliberately does not change a byte of
    // the generated tree -- see `ScaffoldTarget`'s doc. Reading it here keeps the parameter
    // honest for a future per-target template without pretending one exists today.
    let _aimed_at = target;
    let title = title_case(name);
    vec![
        ScaffoldFile::new(
            "omnion.manifest.json",
            manifest(ScaffoldKind::Plugin, name, "dist/index.js", &title),
        ),
        ScaffoldFile::new(
            "src/index.ts",
            format!(
                "// {title}\n\
                 //\n\
                 // A plugin's entry point. The platform calls `activate` once, with the\n\
                 // services it is willing to hand an extension; everything else is yours.\n\
                 import type {{ PluginContext }} from \"@omnion/sdk\";\n\n\
                 export function activate(context: PluginContext) {{\n\
                 \x20 context.log.info(\"{name} activated\");\n\n\
                 \x20 // Register whatever your extension contributes. The two calls below are the\n\
                 \x20 // whole surface for a first run — delete them and add your own.\n\
                 \x20 context.routes.register({{ path: \"/{name}\", handler: hello }});\n\
                 \x20 context.admin.addPanel({{\n\
                 \x20   title: \"{title}\",\n\
                 \x20   render: () => \"<p>Hello from {name}.</p>\",\n\
                 \x20 }});\n\
                 }}\n\n\
                 function hello() {{\n\
                 \x20 return {{ status: 200, body: {{ plugin: \"{name}\" }} }};\n\
                 }}\n",
                title = title,
            ),
        ),
        ScaffoldFile::new(
            "package.json",
            format!(
                "{{\n  \"name\": \"{name}\",\n  \"version\": \"1.0.0\",\n  \"private\": true,\n  \
                 \"type\": \"module\",\n  \"scripts\": {{\n    \"build\": \"tsc -p tsconfig.json\",\n    \
                 \"check\": \"tsc -p tsconfig.json --noEmit\"\n  }},\n  \
                 \"devDependencies\": {{\n    \"@omnion/sdk\": \"^1.0.0\",\n    \
                 \"typescript\": \"^5.0.0\"\n  }}\n}}\n"
            ),
        ),
        ScaffoldFile::new(
            "tsconfig.json",
            "{\n  \"compilerOptions\": {\n    \"target\": \"ES2022\",\n    \"module\": \"ES2022\",\n    \
             \"moduleResolution\": \"bundler\",\n    \"strict\": true,\n    \"outDir\": \"dist\",\n    \
             \"declaration\": true\n  },\n  \"include\": [\"src\"]\n}\n",
        ),
        ScaffoldFile::new(
            "src/types.ts",
            "export interface PluginRecord {\n  id: string;\n  createdAt: string;\n}\n",
        ),
        ScaffoldFile::new(
            ".env.example",
            "# A plugin usually talks to Omnion only through the host, so this file is\n\
             # usually empty. Uncomment if you add an external call.\n\
             # OMNION_BASE_URL=\n# OMNION_TOKEN=\n",
        ),
        gitignore(),
        readme(
            name,
            ScaffoldKind::Plugin,
            "Build with `npm install && npm run build`, then install the folder through the \
             extensions screen.",
        ),
    ]
}

